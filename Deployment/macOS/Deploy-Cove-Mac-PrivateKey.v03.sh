#!/bin/sh
#
# SYNOPSIS
#     Client-side MDM script to deploy Cove | Backup Manager with pre-generated private key credentials
#
# DESCRIPTION
#     CLIENT-SIDE COMPONENT — requires a server-side script to pre-generate devices with private key
#     encryption before this script is deployed via MDM.
#
#     Downloads the generic macOS Backup Manager installer and pre-creates config.ini
#     with Device/Account name, InstallationKey, and EncryptionKey. Supports force uninstallation of prior versions.
#
# USAGE
#     ./Deploy-Cove-Mac-PrivateKey.v03.sh -u <device_name> -p <installation_key> -k <encryption_key> [-d <download_path>] [-f]
#
# OPTIONS
#     -u, --user <device_name>     Mandatory: Device or Account name - lowercase, alphanumeric, hyphens, underscores (from Cove console)
#     -p, --password <inst_key>    Mandatory: InstallationKey - 12 alphanumeric characters (from Cove console)
#     -k, --key <encryption_key>   Mandatory: encryption key (8+ chars: digit, upper, lower, special [@#$%*?!;])
#     -d, --download <path>        Optional: download directory (default: /tmp)
#     -f, --force                  Optional: force uninstallation of prior version
#     -h, --help                   Show this help message
#
# EXAMPLES
#     ./Deploy-Cove-Mac-PrivateKey.v03.sh -u "device-001" -p "74dc06c4fce2" -k ";%c$GPgA4Ep05j?6"
#     ./Deploy-Cove-Mac-PrivateKey.v03.sh -u "device-001" -p "74dc06c4fce2" -k "P@ssw0rd!1234" -f
#     ./Deploy-Cove-Mac-PrivateKey.v03.sh -u "sample01" -p "74dc06c4fce2" -k ";%c$GPgA4Ep05j?6"
#     - Ensure that the script is run with sufficient privileges (sudo) for installation and service management.
#
# NOTES
#     - CLIENT-SIDE ONLY: device credentials must be pre-generated by the server-side script before MDM deployment.
#     - This script requires sudo for service management and installation.
#     - config.ini is created BEFORE installation with User, Password, and EncryptionKey
#     - After installation, it verifies if the BackupFP service is loaded and process is active.
#
